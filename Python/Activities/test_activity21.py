def test_addition():
    num1 = 10
    num2 = 15
    result = num1 + num2
    assert result == 25


def test_subtraction():
    num1 = 50
    num2 = 35
    result = num1 - num2
    assert result == 15


def test_multiplication():
    num1 = 5
    num2 = 20
    result = num1 * num2
    assert result == 100


def test_division():
    num1 = 100
    num2 = 5
    result = num1 / num2
    assert result == 20